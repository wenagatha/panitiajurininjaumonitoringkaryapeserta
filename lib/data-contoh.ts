export const karyaContoh: Karya[] = pesertaContoh.map((peserta, index) => ({
  id: `k-${String(index + 1).padStart(3, "0")}`,
  pesertaId: peserta.id,
  status: statusContoh[index],
  urlKarya: URL_KARYA_DEMO,
  urlPernyataan: URL_PERNYATAAN_DEMO,
}));

export function getPesertaDashboardByKategori(
  kategori: KategoriLomba,
): PesertaDashboard[] {
  const karyaByPeserta = new Map(
    karyaContoh.map((karya) => [karya.pesertaId, karya]),
  );
  return pesertaContoh
    .filter((peserta) => peserta.kategori === kategori)
    .map((peserta) => {
      const karya = karyaByPeserta.get(peserta.id);
      if (!karya) {
        throw new Error(`Karya peserta ${peserta.id} tidak ditemukan.`);
      }
      return { ...peserta, karya };
    });
}
